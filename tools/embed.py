from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = (root / 'web/index.html').read_bytes()
values = ','.join(str(b) for b in data + b'\0')
(root / 'common/web_page.h').write_text('/* Generated by tools/embed.py */\nstatic const char web_page[] = {' + values + '};\n')
print(f'Embedded {len(data)} bytes')
